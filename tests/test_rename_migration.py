"""
Tests for the JARVIS → Raya rename migration. Everything happens in a throwaway
home folder; launchctl / crontab are faked, so nothing on this computer changes.

    .venv/bin/python -m unittest tests.test_rename_migration -v
"""

import json
import sys
import tempfile
import unittest
from pathlib import Path
from types import SimpleNamespace
from unittest import mock

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import memory.config_manager as cm                      # noqa: E402
from core.rename_migration import migrate_legacy_names  # noqa: E402

PLIST = """<plist version="1.0"><dict>
  <key>Label</key><string>{label}</string>
  <key>ProgramArguments</key><array><string>/py</string><string>{script}</string></array>
</dict></plist>
"""


class FakeRun:
    """Stands in for subprocess.run; records calls, answers crontab -l."""

    def __init__(self, crontab: str = ""):
        self.calls, self.crontab = [], crontab

    def __call__(self, cmd, **kw):
        self.calls.append(list(cmd))
        if cmd[:2] == ["crontab", "-l"]:
            return SimpleNamespace(returncode=0, stdout=self.crontab, stderr="")
        if cmd[:2] == ["crontab", "-"]:
            self.crontab = kw.get("input", "")
        return SimpleNamespace(returncode=0, stdout="", stderr="")


class MigrationTests(unittest.TestCase):
    def setUp(self):
        self._td = tempfile.TemporaryDirectory()
        self.home = Path(self._td.name) / "home"
        self.base = Path(self._td.name) / "app"
        (self.base / "config" / "certs").mkdir(parents=True)
        self.cfg = self.base / "config" / "api_keys.json"
        self.cfg.write_text(json.dumps({"gemini_api_key": "KEEP", "assistant_name": "JARVIS"}))
        p = [mock.patch.object(cm, "CONFIG_FILE", self.cfg),
             mock.patch.object(cm, "CONFIG_DIR", self.cfg.parent)]
        for x in p:
            x.start()
            self.addCleanup(x.stop)
        self.addCleanup(self._td.cleanup)

    def w(self, rel: str, text: str = "x") -> Path:
        f = self.home / rel
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(text)
        return f

    def migrate(self, os_name, run):
        return migrate_legacy_names(home=self.home, base_dir=self.base, os_name=os_name, run=run)

    def test_mac_moves_everything_and_reloads_only_scheduled_agents(self):
        h = self.home
        task = "JARVISReminder_20261201_090000"
        old_script = h / ".jarvis" / "reminders" / f"{task}.py"
        self.w(f".jarvis/reminders/{task}.py", '# Auto-generated by J.A.R.V.I.S reminder\ntitle="J.A.R.V.I.S Reminder"\n')
        agents = "Library/LaunchAgents"
        self.w(f"{agents}/com.jarvis.reminder.{task}.plist",
               PLIST.format(label=f"com.jarvis.reminder.{task}", script=old_script))
        self.w(f"{agents}/com.jarvis.assistant.plist", PLIST.format(label="com.jarvis.assistant", script="/app/main.py"))
        self.w(f"{agents}/com.jarvis.gameupdater.plist", PLIST.format(label="com.jarvis.gameupdater", script="/g.py"))
        self.w(".jarvis_profiles/chrome/Cookies", "login")
        self.w(".jarvis_profiles/firefox_jarvis/prefs.js")
        self.w("Documents/JARVIS Uploads/photo.jpg")
        (self.base / "config" / "certs" / "jarvis.key").write_text("KEY")
        (self.base / "config" / "certs" / "jarvis.crt").write_text("CRT")

        run = FakeRun()
        done = self.migrate("mac", run)
        self.assertTrue(done)

        # folders and files
        self.assertEqual((h / ".raya_profiles" / "chrome" / "Cookies").read_text(), "login")
        self.assertTrue((h / ".raya_profiles" / "firefox_raya" / "prefs.js").exists())
        self.assertTrue((h / "Documents" / "Raya Uploads" / "photo.jpg").exists())
        for gone in (".jarvis", ".jarvis_profiles", "Documents/JARVIS Uploads"):
            self.assertFalse((h / gone).exists(), gone)
        certs = self.base / "config" / "certs"
        self.assertEqual((certs / "raya.key").read_text(), "KEY")
        self.assertEqual((certs / "raya.crt").read_text(), "CRT")
        self.assertFalse((certs / "jarvis.key").exists())

        # reminder: script renamed + retitled, agent points at it under the new label
        new_task = "RayaReminder_20261201_090000"
        new_script = h / ".raya" / "reminders" / f"{new_task}.py"
        self.assertIn("Raya Reminder", new_script.read_text())
        self.assertNotIn("J.A.R.V.I.S", new_script.read_text())
        rem = (h / agents / f"com.raya.reminder.{new_task}.plist").read_text()
        self.assertIn(f"<string>com.raya.reminder.{new_task}</string>", rem)
        self.assertIn(str(new_script), rem)
        self.assertNotIn("jarvis", rem.lower())

        # auto-start and game updater renamed; old plists gone
        self.assertIn("com.raya.assistant", (h / agents / "com.raya.assistant.plist").read_text())
        self.assertIn("com.raya.gameupdater", (h / agents / "com.raya.gameupdater.plist").read_text())
        self.assertEqual(list((h / agents).glob("com.jarvis.*")), [])

        # launchctl: reminder and game updater reloaded; auto-start never touched
        flat = [" ".join(c) for c in run.calls]
        self.assertTrue(any(c.startswith("launchctl load") and "com.raya.reminder" in c for c in flat))
        self.assertTrue(any(c.startswith("launchctl load") and "com.raya.gameupdater" in c for c in flat))
        self.assertFalse(any("assistant" in c for c in flat))

        # saved name, key untouched
        cfg = json.loads(self.cfg.read_text())
        self.assertEqual(cfg["assistant_name"], "Raya")
        self.assertEqual(cfg["gemini_api_key"], "KEEP")

        # second run: nothing left to do
        run2 = FakeRun()
        self.assertEqual(self.migrate("mac", run2), [])
        self.assertEqual(run2.calls, [])

    def test_merges_when_both_folders_exist_and_keeps_clashes(self):
        self.w(".jarvis_profiles/chrome/old_only")
        self.w(".jarvis_profiles/chrome/both", "old")
        self.w(".raya_profiles/chrome/both", "new")
        self.migrate("mac", FakeRun())
        d = self.home / ".raya_profiles" / "chrome"
        self.assertTrue((d / "old_only").exists())
        self.assertEqual((d / "both").read_text(), "new")
        # the clashing old file is kept rather than lost
        self.assertEqual((self.home / ".jarvis_profiles" / "chrome" / "both").read_text(), "old")

    def test_custom_assistant_name_is_kept(self):
        self.cfg.write_text(json.dumps({"gemini_api_key": "KEEP", "assistant_name": "E V"}))
        self.migrate("mac", FakeRun())
        self.assertEqual(json.loads(self.cfg.read_text())["assistant_name"], "E V")

    def test_linux_keeps_pending_reminders_and_renames_autostart_and_cron(self):
        self.w(".jarvis/reminders/JARVISReminder_1.py")
        self.w(".config/autostart/jarvis.desktop", "[Desktop Entry]\n")
        run = FakeRun(crontab="0 3 * * * /py /g.py --scheduled  # JARVIS_GameUpdater\n")
        self.migrate("linux", run)
        self.assertTrue((self.home / ".jarvis" / "reminders" / "JARVISReminder_1.py").exists())
        self.assertTrue((self.home / ".config" / "autostart" / "raya.desktop").exists())
        self.assertIn("# Raya_GameUpdater", run.crontab)
        self.assertNotIn("JARVIS", run.crontab)
        self.assertTrue((self.home / ".raya" / ".renamed-from-jarvis").exists())

        # once the reminder has fired (script gone), the empty old folder is removed
        (self.home / ".jarvis" / "reminders" / "JARVISReminder_1.py").unlink()
        run2 = FakeRun()
        self.migrate("linux", run2)
        self.assertFalse((self.home / ".jarvis").exists())
        self.assertEqual(run2.calls, [])          # cron already done: marker skips it

    def test_a_failing_step_does_not_stop_the_rest(self):
        self.w(".jarvis_profiles/chrome/x")
        with mock.patch("core.rename_migration._Migration.certs", side_effect=OSError("boom")):
            self.migrate("mac", FakeRun())
        self.assertTrue((self.home / ".raya_profiles" / "chrome" / "x").exists())
        self.assertEqual(json.loads(self.cfg.read_text())["assistant_name"], "Raya")


if __name__ == "__main__":
    unittest.main()
